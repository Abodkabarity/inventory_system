    def test_10_online_stale_generations_and_exact_user_restriction(self):
        allowed = '94c7aa76-bc23-40e4-8c9a-f2cb9636c821'
        with self.c.transaction(force_rollback=True):
            self.claims(allowed)
            calls = [
                ('online_overview_private.read_batch',('stale','','onlineOnly',0,5000)),
                ('online_overview_private.recent_sales',('stale','missing','')),
                ('online_overview_private.stock_breakdown',('stale','missing')),
                ('online_overview_private.forecast_details',('stale','missing')),
                ('online_overview_private.monthly_sales',('stale','missing','')),
                ('online_overview_private.branch_availability',('stale',)),
                ('online_overview_preview_private.monthly_sales',('stale','missing','')),
                ('online_overview_preview_private.recent_sales',('stale','missing','')),
                ('online_overview_preview_private.read',('batch','stale','','onlineOnly',0,5000,'missing')),
            ]
            for name, args in calls:
                with self.subTest(function=name):
                    self.expect_error('select '+name+'('+','.join(['%s']*len(args))+')',args,'PT409')
            other = self.c.execute("select user_id from public.app_users where is_active and lower(btrim(role))='inventory' and user_id<>%s::uuid limit 1",(allowed,)).fetchone()
            self.claims(other['user_id'] if other else uuid4())
            self.expect_error("select online_overview_private.branch_availability('stale')",(),'42501')
            self.c.execute("select set_config('request.jwt.claims','{}',true),set_config('request.jwt.claim.sub','',true)")
            self.expect_error("select online_overview_private.branch_availability('stale')",(),'42501')

