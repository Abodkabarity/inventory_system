"""Verify the conflict migration in a rollback transaction and isolated temp fixtures.

No production business rows are changed. Uses the connection settings of
cleanup_duplicate_indexes.py and requires the migration owner's connection.
"""
import json
import re
import unittest
from datetime import date
from pathlib import Path
from uuid import uuid4

import psycopg
from psycopg.types.json import Jsonb

from cleanup_duplicate_indexes import connect

ROOT = Path(__file__).resolve().parents[1]


class ConflictGuards(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.c = connect()
        cls.tx = cls.c.transaction(force_rollback=True)
        cls.tx.__enter__()
        try:
            cls.c.execute("set local lock_timeout='1s'")
            cls.c.execute("set local statement_timeout='30s'")
            cls.before = cls.functions()
            migration = next((ROOT / 'supabase/migrations').glob('*_prevent_application_conflict_retry_loops.sql'))
            cls.c.execute(migration.read_text())
            cls.after = cls.functions()
            cls.c.execute("select set_config('cpu.role','inventory',true)")
            cls.inventory = cls.c.execute("select user_id from public.app_users where is_active and lower(btrim(role))='inventory' limit 1").fetchone()['user_id']
            cls.claims(cls.inventory)
            cls.c.execute("""create function pg_temp.cpu_role() returns text language sql as
              'select current_setting(''cpu.role'',true)';
              create temp table cpu_items as select * from public.items_tracker_items limit 1;
              create temp table cpu_events as select * from public.items_tracker_events with no data;
              alter table cpu_events alter column id set not null;
              alter table cpu_events alter column id add generated by default as identity;
              update cpu_items set row_version=1,follow_up_role='inventory',case_status='pending';""")
            cls.item = cls.c.execute('select id,item_code from cpu_items').fetchone()
            if cls.item is None:
                raise AssertionError('An Items Tracker sample is required')
            for f in cls.after.values():
                if f['proname'].startswith('item_tracker_'):
                    cls.clone(f['definition'], 'public', f['proname'], {
                        'public.items_tracker_items': 'pg_temp.cpu_items',
                        'public.items_tracker_events': 'pg_temp.cpu_events',
                        'RETURNS items_tracker_items': 'RETURNS pg_temp.cpu_items',
                        'RETURNS items_tracker_events': 'RETURNS pg_temp.cpu_events',
                        'public.item_tracker_my_role()': 'pg_temp.cpu_role()',
                        'public.item_tracker_add_action(': 'pg_temp.cpu_item_tracker_add_action(',
                    })
        except BaseException:
            cls.tx.__exit__(None, None, None)
            cls.c.close()
            raise

    @classmethod
    def tearDownClass(cls):
        cls.tx.__exit__(None, None, None)
        cls.c.close()

    @classmethod
    def functions(cls):
        rows = cls.c.execute("""select p.oid,p.oid::regprocedure::text as signature,p.proname,
          pg_get_functiondef(p.oid) as definition,p.prosrc,p.proacl,p.proowner,p.proconfig,
          p.prosecdef,p.provolatile from pg_proc p join pg_namespace n on n.oid=p.pronamespace
          where p.prokind='f' and n.nspname not in ('pg_catalog','information_schema','pg_temp_1')
          and (p.prosrc like '%%40001%%' or p.prosrc like '%%PT409%%')""").fetchall()
        return {row['signature']: row for row in rows if not row['signature'].startswith('pg_temp')}

    @classmethod
    def claims(cls, uid):
        cls.c.execute("select set_config('request.jwt.claims',%s,true),set_config('request.jwt.claim.sub',%s,true)",
                      (json.dumps({'sub': str(uid), 'role': 'authenticated'}), str(uid)))

    @classmethod
    def clone(cls, definition, schema, name, replacements):
        definition = definition.replace('FUNCTION ' + schema + '.' + name + '(', 'FUNCTION pg_temp.cpu_' + name + '(')
        for old, new in replacements.items():
            definition = definition.replace(old, new)
        cls.c.execute(definition)

    def expect_error(self, query, params, code, message=None):
        try:
            with self.c.transaction(force_rollback=True):
                self.c.execute(query, params)
        except psycopg.Error as error:
            self.assertEqual(error.sqlstate, code)
            if message:
                self.assertEqual(error.diag.message_primary, message)
        else:
            self.fail('Conflict/permission guard accepted the request')

    def test_01_only_error_codes_and_import_handler_change(self):
        changed = 0
        for signature, before in self.before.items():
            after = self.after[signature]
            expected = before['definition']
            if not signature.startswith('online_overview'):
                expected = re.sub(r"(errcode\s*=\s*)'40001'", r"\g<1>'PT409'", expected, flags=re.I)
                if before['proname'] == 'item_tracker_import_actions':
                    expected = expected.replace("when sqlstate '40001' then", "when sqlstate '40001' or sqlstate 'PT409' then")
            self.assertEqual(after['definition'], expected, signature)
            for field in ('oid','proacl','proowner','proconfig','prosecdef','provolatile'):
                self.assertEqual(after[field], before[field], (signature, field))
            changed += before['definition'] != after['definition']
        # Re-running against an already repaired database is also supported.
        self.assertIn(changed, (0, 14))

    def test_02_tracker_stale_versions_do_not_write(self):
        item = self.item['id']
        calls = {
            'item_tracker_add_action': (item,date.today(),'Guard test','pending',2),
            'item_tracker_change_follow_up': (item,'purchase','Guard test',date.today(),2),
            'item_tracker_update_tracker_status': (item,'done',2),
            'item_tracker_update_status_updated_to': (item,'Normal Purchase',2),
            'item_tracker_update_status_updated_to_apg': (item,'Normal Purchase',2),
            'item_tracker_update_inventory_fields': (item,date.today(),1,'Guard test',1,'Normal Purchase','inventory',2),
            'item_tracker_update_inventory_fields_apg': (item,date.today(),1,'Guard test',1,'Normal Purchase','inventory',2),
        }
        before = self.c.execute('select to_jsonb(t) as doc from cpu_items t').fetchone()
        for name, params in calls.items():
            with self.subTest(function=name):
                self.expect_error('select pg_temp.cpu_' + name + '(' + ','.join(['%s'] * len(params)) + ')',
                                  params, 'PT409', 'STALE_ITEM_VERSION')
        self.assertEqual(before, self.c.execute('select to_jsonb(t) as doc from cpu_items t').fetchone())
        self.assertEqual(self.c.execute('select count(*) as n from cpu_events').fetchone()['n'], 0)

    def test_03_tracker_permissions_and_valid_action(self):
        self.c.execute("select set_config('cpu.role','purchase',true)")
        self.expect_error('select pg_temp.cpu_item_tracker_update_status_updated_to(%s,%s,%s)',
                          (self.item['id'],'Normal Purchase',1), '42501')
        self.c.execute("select set_config('cpu.role','inventory',true)")
        with self.c.transaction(force_rollback=True):
            self.c.execute('select pg_temp.cpu_item_tracker_add_action(%s,%s,%s,%s,%s)',
                            (self.item['id'],date.today(),'Valid action','pending',1))
            self.assertEqual(self.c.execute('select body from cpu_events').fetchone()['body'], 'Valid action')

    def test_04_import_preserves_conflict_result_for_both_codes(self):
        payload = [{'item_id': str(self.item['id']), 'item_code': self.item['item_code'],
                    'import_token': str(uuid4()), 'expected_version': 1, 'body': 'Import guard', 'excel_row': 2}]
        for code in ('PT409','40001'):
            with self.subTest(code=code), self.c.transaction(force_rollback=True):
                self.c.execute("""create or replace function pg_temp.cpu_item_tracker_add_action(
                  p_item_id uuid,p_action_date date,p_body text,p_case_status text,p_expected_version bigint)
                  returns pg_temp.cpu_events language plpgsql as
                  $stub$ begin raise exception 'STALE_ITEM_VERSION' using errcode='""" + code + "'; end; $stub$")
                result = self.c.execute('select pg_temp.cpu_item_tracker_import_actions(%s,%s,%s) as result',
                                        (Jsonb(payload),'guard-test.xlsx',True)).fetchone()['result']
                self.assertEqual(result[0]['status'], 'conflict')
                self.assertEqual(result[0]['message'], 'Product changed during import; system data kept.')
                self.assertEqual(self.c.execute('select count(*) as n from cpu_events').fetchone()['n'], 0)

    def test_05_upp_snapshot_and_permission_guards(self):
        first = self.c.execute('select public.upp_index_page(0,1,null) as doc').fetchone()['doc']
        same = self.c.execute('select public.upp_index_page(0,1,%s) as doc',(first['snapshot'],)).fetchone()['doc']
        self.assertEqual(first, same)
        self.expect_error('select public.upp_index_page(0,1,%s)', ('stale-snapshot',), 'PT409')
        with self.c.transaction(force_rollback=True):
            self.claims('00000000-0000-0000-0000-000000000000')
            self.expect_error('select public.upp_index_page(0,1,null)', (), '42501')

    def test_06_expiry_fingerprint_and_version_guards(self):
        with self.c.transaction(force_rollback=True):
            self.c.execute('''create temp table cpu_candidates as select * from public.stock_expiry_candidates with no data;
              create temp table cpu_receipt_reviews as select * from public.stock_expiry_receipt_reviews with no data;
              create unique index on cpu_receipt_reviews(item_code,expiry_date,mrn_date);
              insert into cpu_candidates(item_code,expiry_date,last_receipt_date,receipt_fingerprint)
              values('__cpu_guard__',current_date+60,current_date-1,'current');''')
            f = next(v for v in self.after.values() if v['proname']=='save_expiry_review')
            self.clone(f['definition'],'stock_management_private','save_expiry_review',{
                'public.stock_expiry_candidates':'pg_temp.cpu_candidates',
                'public.stock_expiry_receipt_reviews':'pg_temp.cpu_receipt_reviews',
                'public.item_tracker_my_role()':'pg_temp.cpu_role()',
            })
            days = self.c.execute('select current_date+60 as expiry,current_date-1 as mrn').fetchone()
            params = ('__cpu_guard__',days['expiry'],'old','Original note','review',None,days['mrn'])
            self.expect_error('select pg_temp.cpu_save_expiry_review(%s,%s,%s,%s,%s,%s,%s)', params, 'PT409')
            params = (*params[:2],'current',*params[3:])
            saved = self.c.execute('select pg_temp.cpu_save_expiry_review(%s,%s,%s,%s,%s,%s,%s) as doc',params).fetchone()['doc']
            self.assertTrue(saved['is_reviewed'])
            self.expect_error('select pg_temp.cpu_save_expiry_review(%s,%s,%s,%s,%s,%s,%s)',params,'PT409')
            self.assertEqual(self.c.execute('select note from cpu_receipt_reviews').fetchone()['note'],'Original note')

    def test_07_branch_revision_selection_and_entry_guards(self):
        with self.c.transaction(force_rollback=True):
            self.c.execute('''
              create temp table cpu_months as select * from branch_near_expiry_private.months with no data;
              create temp table cpu_near_entries as select * from public.stock_take_near_expiry_items with no data;
              create temp table cpu_sessions as select * from public.stock_take_sessions with no data;
              create function pg_temp.cpu_access(text) returns boolean language sql as 'select true';
              create function pg_temp.cpu_branch_role() returns text language sql as $$select 'inventory'::text$$;
              create function pg_temp.cpu_lock_month(text,date) returns void language plpgsql as $$begin return; end$$;
              create function pg_temp.cpu_rows(text,date) returns table(doc jsonb) language sql as
                'select null::jsonb where false';
              insert into cpu_months(branch_name,month,revision)
              values('__cpu_branch__',date_trunc('month',now() at time zone 'Asia/Dubai')::date,1);
            ''')
            session, entry = uuid4(), uuid4()
            self.c.execute('''insert into cpu_sessions(id,branch_name,source_kind,status,created_at,source_created_at)
              values(%s,'__cpu_branch__','near_expiry','draft',now(),now());''',(session,))
            self.c.execute('''insert into cpu_near_entries(id,session_id,quantity,expiry_date,updated_at)
              values(%s,%s,1,current_date+60,now())''',(entry,session))
            f = next(v for v in self.after.values() if v['proname']=='workspace' and 'branch_near_expiry' in v['signature'])
            self.clone(f['definition'],'branch_near_expiry_private','workspace',{
                'branch_near_expiry_private.months':'pg_temp.cpu_months',
                'public.stock_take_near_expiry_items':'pg_temp.cpu_near_entries',
                'public.stock_take_sessions':'pg_temp.cpu_sessions',
                'stock_take_private.can_access_branch(':'pg_temp.cpu_access(',
                'stock_take_private.current_user_role()':'pg_temp.cpu_branch_role()',
                'branch_near_expiry_private.lock_month(':'pg_temp.cpu_lock_month(',
                'branch_near_expiry_private.rows(':'pg_temp.cpu_rows(',
            })
            cases = [
                ('delete',{'revision':0,'id':str(entry)}),
                ('delete_selected',{'revision':1,'ids':[str(entry)]}),
                ('delete',{'revision':1,'id':str(entry),'expected_quantity':2}),
            ]
            for action, payload in cases:
                with self.subTest(action=action,payload=payload):
                    self.expect_error('select pg_temp.cpu_workspace(%s,%s,%s)',
                                      ('__cpu_branch__',action,Jsonb(payload)),'PT409')
            kept = self.c.execute('select quantity,deleted_at from cpu_near_entries').fetchone()
            self.assertEqual(kept['quantity'],1)
            self.assertIsNone(kept['deleted_at'])

    def test_08_expiry_prepare_source_change_guard(self):
        with self.c.transaction(force_rollback=True):
            self.c.execute('''create temp table cpu_prepare_calls(n integer);
              insert into cpu_prepare_calls values(0);
              create function pg_temp.cpu_state() returns jsonb language plpgsql as $body$
              declare calls integer; begin
                update pg_temp.cpu_prepare_calls set n=n+1 returning n into calls;
                return jsonb_build_object('discovery',case when calls=1 then 'old' else 'new' end);
              end; $body$;
              create function pg_temp.cpu_refresh_watch() returns void language plpgsql as $$begin return; end$$;
            ''')
            f = next(v for v in self.after.values() if v['proname']=='prepare_stock_expiry_workspace')
            self.clone(f['definition'],'public',f['proname'],{
                'public.get_stock_workspace_cache_state()':'pg_temp.cpu_state()',
                'public.refresh_stock_expiry_watch()':'pg_temp.cpu_refresh_watch()',
            })
            self.expect_error('select pg_temp.cpu_prepare_stock_expiry_workspace(%s)',('old',),'PT409')

