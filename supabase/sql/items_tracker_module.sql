create or replace function public.item_tracker_register_attachment(
  p_item_id uuid,
  p_storage_path text,
  p_file_name text,
  p_mime_type text,
  p_file_size bigint
)
returns public.items_tracker_attachments
language plpgsql
security definer
set search_path = pg_catalog, public, storage
as $$
declare
  v_role text := public.item_tracker_my_role();
  v_event public.items_tracker_events%rowtype;
  v_attachment public.items_tracker_attachments%rowtype;
  v_expected_prefix text;
  v_activity_event_id bigint;
  v_activity_actor_id uuid;
begin
  if v_role is null then
    raise exception 'ITEMS_TRACKER_PERMISSION_REQUIRED'
      using errcode = '42501';
  end if;

  if nullif(btrim(coalesce(p_file_name, '')), '') is null then
    raise exception 'ATTACHMENT_FILE_NAME_REQUIRED'
      using errcode = '22023';
  end if;

  if p_mime_type not in (
    'application/pdf',
    'image/jpeg',
    'image/png',
    'image/webp'
  ) then
    raise exception 'ATTACHMENT_TYPE_NOT_ALLOWED'
      using errcode = '22023';
  end if;

  if p_file_size is null or p_file_size <= 0 or p_file_size > 15728640 then
    raise exception 'ATTACHMENT_SIZE_NOT_ALLOWED'
      using errcode = '22023';
  end if;

  perform 1 from public.items_tracker_items where id = p_item_id for update;

  if not found then
    raise exception 'ITEMS_TRACKER_ITEM_NOT_FOUND'
      using errcode = 'P0002';
  end if;

  select e.id, e.actor_id
  into v_activity_event_id, v_activity_actor_id
  from public.items_tracker_events e
  where e.item_id = p_item_id
    and e.event_type in ('action', 'follow_up')
  order by e.created_at desc, e.id desc
  limit 1;

  if v_activity_event_id is null or v_activity_actor_id <> auth.uid() then
    raise exception 'ATTACHMENT_REQUIRES_YOUR_LATEST_ACTIVITY'
      using errcode = '42501';
  end if;

  v_expected_prefix := p_item_id::text || '/' || auth.uid()::text || '/';
  if p_storage_path is null
    or left(p_storage_path, length(v_expected_prefix)) <> v_expected_prefix then
    raise exception 'INVALID_ATTACHMENT_STORAGE_PATH'
      using errcode = '22023';
  end if;

  perform 1
  from storage.objects o
  where o.bucket_id = 'items-tracker-files'
    and o.name = p_storage_path
    and coalesce(o.owner_id::text, '') = auth.uid()::text;

  if not found then
    raise exception 'ATTACHMENT_OBJECT_NOT_FOUND_OR_NOT_OWNED'
      using errcode = '42501';
  end if;

  insert into public.items_tracker_events (
    item_id,
    event_type,
    body,
    details,
    actor_id,
    actor_role
  ) values (
    p_item_id,
    'file_uploaded',
    'Uploaded file: ' || btrim(p_file_name),
    jsonb_build_object(
      'file_name', btrim(p_file_name),
      'mime_type', p_mime_type,
      'file_size', p_file_size,
      'storage_path', p_storage_path
    ),
    auth.uid(),
    v_role
  )
  returning * into v_event;

  insert into public.items_tracker_attachments (
    item_id,
    event_id,
    activity_event_id,
    bucket_name,
    storage_path,
    file_name,
    mime_type,
    file_size,
    created_by,
    created_by_role
  ) values (
    p_item_id,
    v_event.id,
    v_activity_event_id,
    'items-tracker-files',
    p_storage_path,
    btrim(p_file_name),
    p_mime_type,
    p_file_size,
    auth.uid(),
    v_role
  )
  returning * into v_attachment;

  update public.items_tracker_items
  set
    updated_by = auth.uid(),
    updated_by_role = v_role
  where id = p_item_id;

  return v_attachment;
end;
$$;

