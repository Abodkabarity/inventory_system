-- Items Tracker module
--
-- Run this migration once from the Supabase SQL editor. It is safe to rerun:
-- tables and indexes use IF NOT EXISTS, while functions, triggers, views, and
-- policies are replaced deterministically.
--
-- Important data rule: item_report.retail is saved only as retail_snapshot.
-- It is never treated as item cost. unit_cost_snapshot is an optional manual
-- Inventory input and required_value remains NULL when no unit cost is entered.

begin;

-- purchase_status_module.sql already removes this conventional constraint.
-- Repeating the operation here keeps standalone installations able to assign
-- the new app_users.role = 'category' value without guessing every legacy role.
alter table if exists public.app_users
  drop constraint if exists app_users_role_check;

create or replace function public.item_tracker_my_role()
returns text
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select lower(btrim(au.role::text))
  from public.app_users au
  where au.user_id = auth.uid()
    and au.is_active is not false
    and lower(btrim(au.role::text)) in ('inventory', 'purchase', 'category')
  limit 1;
$$;

create table if not exists public.items_tracker_items (
  id uuid primary key default gen_random_uuid(),
  escalated_date date not null
    default ((now() at time zone 'Asia/Dubai')::date),

  -- Immutable catalog snapshots captured when Inventory creates the case.
  item_code text not null,
  item_name text not null,
  category text,
  supplier text,
  company text,
  source_item_status text,
  retail_snapshot numeric(20, 4),

  -- Optional manual Inventory value. Retail is deliberately not a fallback.
  unit_cost_snapshot numeric(20, 4),
  unit_cost_source text,
  inventory_note text,
  required_qty numeric(20, 3) not null,
  required_value numeric(24, 2) generated always as (
    case
      when unit_cost_snapshot is null then null
      else round(unit_cost_snapshot * required_qty, 2)
    end
  ) stored,

  status_updated_to text not null,
  follow_up_role text not null,
  case_status text not null default 'pending',

  created_by uuid not null default auth.uid(),
  created_by_role text not null,
  created_at timestamptz not null default now(),
  updated_by uuid not null default auth.uid(),
  updated_by_role text not null,
  updated_at timestamptz not null default now(),
  row_version bigint not null default 1,
  closed_at timestamptz,
  closed_by uuid,

  constraint items_tracker_items_code_not_blank
    check (btrim(item_code) <> ''),
  constraint items_tracker_items_name_not_blank
    check (btrim(item_name) <> ''),
  constraint items_tracker_items_qty_positive
    check (required_qty > 0),
  constraint items_tracker_items_retail_nonnegative
    check (retail_snapshot is null or retail_snapshot >= 0),
  constraint items_tracker_items_cost_nonnegative
    check (unit_cost_snapshot is null or unit_cost_snapshot >= 0),
  constraint items_tracker_items_cost_source_consistent
    check (
      (unit_cost_snapshot is null and unit_cost_source is null)
      or
      (unit_cost_snapshot is not null and btrim(coalesce(unit_cost_source, '')) <> '')
    ),
  constraint items_tracker_items_status_updated_not_blank
    check (btrim(status_updated_to) <> ''),
  constraint items_tracker_items_follow_up_role_check
    check (follow_up_role in ('inventory', 'purchase', 'category')),
  constraint items_tracker_items_case_status_check
    check (case_status in ('pending', 'done')),
  constraint items_tracker_items_created_role_check
    check (created_by_role in ('inventory', 'purchase', 'category')),
  constraint items_tracker_items_updated_role_check
    check (updated_by_role in ('inventory', 'purchase', 'category'))
);

