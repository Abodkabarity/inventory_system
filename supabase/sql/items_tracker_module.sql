-- Catalog autocomplete. All returned values are catalog values; no client
-- supplied snapshot is trusted by items_tracker_create().
create or replace function public.item_tracker_search_catalog(
  p_query text,
  p_limit integer default 15
)
returns table (
  item_code text,
  item_name text,
  category text,
  supplier text,
  company text,
  item_status text,
  retail numeric
)
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_role text := public.item_tracker_my_role();
  v_query text := btrim(coalesce(p_query, ''));
  v_limit integer := least(greatest(coalesce(p_limit, 15), 1), 50);
begin
  if v_role is null then
    raise exception 'ITEMS_TRACKER_PERMISSION_REQUIRED'
      using errcode = '42501';
  end if;

  if v_query = '' then
    return;
  end if;

  return query
  select
    ir.item_code::text,
    ir.item_name::text,
    ir.category::text,
    ir.supplier::text,
    ir.company::text,
    ir.item_status::text,
    ir.retail::numeric
  from public.item_report ir
  where ir.item_code::text ilike ('%' || v_query || '%')
     or ir.item_name::text ilike ('%' || v_query || '%')
  order by
    case
      when lower(btrim(ir.item_code::text)) = lower(v_query) then 0
      when lower(btrim(ir.item_name::text)) = lower(v_query) then 1
      when lower(ir.item_code::text) like lower(v_query) || '%' then 2
      else 3
    end,
    ir.item_name::text,
    ir.item_code::text
  limit v_limit;
end;
$$;

create or replace function public.item_tracker_status_options()
