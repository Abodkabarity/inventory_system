set case_status = case
  when case_status in ('resolved', 'closed', 'done') then 'done'
  else 'pending'
end
where case_status not in ('pending', 'done');

update public.items_tracker_events
set
  from_case_status = case
    when from_case_status in ('resolved', 'closed', 'done') then 'done'
    when from_case_status is null then null
    else 'pending'
  end,
  to_case_status = case
    when to_case_status in ('resolved', 'closed', 'done') then 'done'
    when to_case_status is null then null
    else 'pending'
  end
where from_case_status not in ('pending', 'done')
   or to_case_status not in ('pending', 'done');

