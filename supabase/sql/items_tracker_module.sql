-- Realtime is optional. The guarded block does nothing when the publication is
-- unavailable or the migration runner cannot alter it.
do $$
declare
  v_table text;
begin
  if exists (
    select 1
    from pg_catalog.pg_publication
    where pubname = 'supabase_realtime'
  ) then
    foreach v_table in array array[
      'items_tracker_items',
      'items_tracker_events',
      'items_tracker_comments',
      'items_tracker_attachments'
    ]
    loop
      begin
        if not exists (
          select 1
          from pg_catalog.pg_publication_tables
          where pubname = 'supabase_realtime'
            and schemaname = 'public'
            and tablename = v_table
        ) then
          execute format(
            'alter publication supabase_realtime add table public.%I',
            v_table
          );
        end if;
      exception
        when duplicate_object or insufficient_privilege or undefined_object
          then null;
      end;
    end loop;
  end if;
end;
$$;

